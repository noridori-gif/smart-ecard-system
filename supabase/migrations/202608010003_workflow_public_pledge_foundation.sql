create or replace function public.create_public_pledge_link(target_event_id bigint,supplied_token_hash text,link_title text,link_message text,link_language text,link_expires_at timestamptz)
returns public.public_pledge_links language plpgsql security definer set search_path=public,auth,pg_catalog as $$
declare result public.public_pledge_links%rowtype;
begin
  if not public.can_manage_event_finance(target_event_id) then raise exception 'Not authorized'; end if;
  if supplied_token_hash is null or supplied_token_hash !~ '^[a-f0-9]{64}$' then raise exception 'Invalid token'; end if;
  if link_language not in ('sw','en') or (link_expires_at is not null and link_expires_at <= now()) then raise exception 'Invalid link settings'; end if;
  insert into public.public_pledge_links(event_id,token_hash,title,message,default_language,expires_at)
  values(target_event_id,supplied_token_hash,nullif(btrim(link_title),''),nullif(btrim(link_message),''),link_language,link_expires_at) returning * into result;
  insert into public.finance_audit_logs(event_id,actor_type,actor_user_id,action,new_data)
  values(target_event_id,'authenticated_user',auth.uid(),'public_pledge_link_created',jsonb_build_object('link_id',result.id,'expires_at',result.expires_at,'language',result.default_language));
  return result;
end $$;

create or replace function public.update_public_pledge_link(target_link_id bigint,link_active boolean,link_expires_at timestamptz,link_title text,link_message text,link_language text)
returns public.public_pledge_links language plpgsql security definer set search_path=public,auth,pg_catalog as $$
declare current_link public.public_pledge_links%rowtype; result public.public_pledge_links%rowtype;
begin
  select * into current_link from public.public_pledge_links where id=target_link_id for update;
  if not found or not public.can_manage_event_finance(current_link.event_id) then raise exception 'Not authorized'; end if;
  if link_language not in ('sw','en') then raise exception 'Invalid link settings'; end if;
  update public.public_pledge_links set is_active=link_active,expires_at=link_expires_at,title=nullif(btrim(link_title),''),message=nullif(btrim(link_message),''),default_language=link_language where id=target_link_id returning * into result;
  insert into public.finance_audit_logs(event_id,actor_type,actor_user_id,action,new_data)
  values(result.event_id,'authenticated_user',auth.uid(),case when link_active then 'public_pledge_link_updated' else 'public_pledge_link_revoked' end,jsonb_build_object('link_id',result.id,'is_active',result.is_active,'expires_at',result.expires_at));
  return result;
end $$;

create or replace function public.get_public_pledge_link(supplied_token_hash text)
returns jsonb language sql stable security definer set search_path=public,pg_catalog as $$
  select case when l.id is null then null else jsonb_build_object('valid',l.is_active and (l.expires_at is null or l.expires_at>now()),'event_name',e.title,'title',l.title,'message',l.message,'language',l.default_language) end
  from public.public_pledge_links l join public.events e on e.id=l.event_id where l.token_hash=supplied_token_hash limit 1
$$;

create or replace function public.submit_public_pledge(supplied_token_hash text,submission_key text,submitter_name text,submitter_phone text,submitter_email text,amount numeric,expected_date date,submitter_note text,request_ip_hash text)
returns jsonb language plpgsql security definer set search_path=public,pg_catalog as $$
declare link public.public_pledge_links%rowtype; normalized_name text; matches bigint[]; match_count int; new_pledge_id bigint; review_id bigint; window_start timestamptz; existing_result jsonb;
begin
  if supplied_token_hash is null or supplied_token_hash !~ '^[a-f0-9]{64}$' or submission_key is null or length(submission_key) not between 16 and 100 then raise exception 'LINK_UNAVAILABLE'; end if;
  select payload->'public_receipt' into existing_result from public.workflow_events where idempotency_key='public:'||submission_key;
  if existing_result is not null then return existing_result; end if;
  select * into link from public.public_pledge_links where token_hash=supplied_token_hash for update;
  if not found or not link.is_active or (link.expires_at is not null and link.expires_at<=now()) then raise exception 'LINK_UNAVAILABLE'; end if;
  window_start := date_trunc('hour',now());
  insert into public.public_pledge_rate_limits(token_hash,ip_hash,window_started_at) values(supplied_token_hash,request_ip_hash,window_start)
  on conflict(token_hash,ip_hash,window_started_at) do update set request_count=public.public_pledge_rate_limits.request_count+1 returning request_count into match_count;
  if match_count>10 then raise exception 'RATE_LIMITED'; end if;
  normalized_name:=lower(regexp_replace(btrim(coalesce(submitter_name,'')),'\s+',' ','g'));
  if length(normalized_name)<2 or amount is null or amount<=0 or amount>1000000000 then raise exception 'INVALID_SUBMISSION'; end if;
  if submitter_phone is not null and submitter_phone !~ '^255[67][0-9]{8}$' then raise exception 'INVALID_SUBMISSION'; end if;
  if submitter_email is not null and (length(submitter_email)>254 or submitter_email !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$') then raise exception 'INVALID_SUBMISSION'; end if;
  if expected_date is not null and expected_date<current_date-interval '31 days' then raise exception 'INVALID_SUBMISSION'; end if;
  if submitter_phone is not null then select array_agg(id) into matches from public.event_pledges where event_id=link.event_id and normalized_phone=submitter_phone and cancelled_at is null;
  else select array_agg(id) into matches from public.event_pledges where event_id=link.event_id and lower(regexp_replace(btrim(full_name),'\s+',' ','g'))=normalized_name and cancelled_at is null; end if;
  match_count:=coalesce(cardinality(matches),0);
  if match_count=0 then
    insert into public.event_pledges(event_id,full_name,phone,normalized_phone,email,pledged_amount,notes,created_by,source,public_pledge_link_id,expected_completion_date)
    values(link.event_id,btrim(submitter_name),submitter_phone,submitter_phone,nullif(lower(btrim(submitter_email)),''),amount,nullif(btrim(submitter_note),''),null,'public_pledge_link',link.id,expected_date) returning id into new_pledge_id;
    delete from public.finance_audit_logs audit where audit.pledge_id=new_pledge_id and audit.actor_user_id is null and audit.action='pledge_created' and audit.created_at>=transaction_timestamp();
  else
    new_pledge_id:=case when match_count=1 then matches[1] else null end;
    insert into public.public_pledge_reviews(event_id,link_id,matched_pledge_ids,submitted_data,reason,idempotency_key)
    values(link.event_id,link.id,matches,jsonb_build_object('full_name',btrim(submitter_name),'phone',submitter_phone,'email',submitter_email,'amount',amount,'expected_date',expected_date,'note',submitter_note),case when match_count>1 then 'ambiguous_match' else 'adjustment_requested' end,submission_key) returning id into review_id;
  end if;
  update public.public_pledge_links set submission_count=submission_count+1,last_used_at=now() where id=link.id;
  insert into public.finance_audit_logs(event_id,pledge_id,actor_type,action,new_data,metadata)
  values(link.event_id,new_pledge_id,'system',case when review_id is null then 'public_pledge_submitted' else 'public_pledge_review_required' end,jsonb_build_object('amount',amount,'source','public_pledge_link'),jsonb_build_object('link_id',link.id,'review_id',review_id));
  existing_result := jsonb_build_object(
    'status',
    case
      when review_id is null then 'received'
      else 'review'
    end,
    'receipt',
    encode(extensions.gen_random_bytes(9), 'hex')
  );
  insert into public.workflow_events(event_id,event_type,entity_type,entity_id,source,payload,idempotency_key)
  values(link.event_id,'pledge.submitted',case when review_id is null then 'pledge' else 'pledge_review' end,coalesce(new_pledge_id,review_id)::text,'public_pledge_link',jsonb_build_object('pledge_id',new_pledge_id,'review_id',review_id,'public_receipt',existing_result),'public:'||submission_key);
  if new_pledge_id is not null and submitter_phone is not null then
    insert into public.workflow_events(event_id,event_type,entity_type,entity_id,source,payload,idempotency_key)
    values(link.event_id,'message.acknowledgement.requested','pledge',new_pledge_id::text,'public_pledge_link',jsonb_build_object('pledge_id',new_pledge_id,'language',link.default_language),'ack:'||submission_key);
    insert into public.finance_audit_logs(event_id,pledge_id,actor_type,action,metadata) values(link.event_id,new_pledge_id,'system','acknowledgement_queued',jsonb_build_object('workflow_key','ack:'||submission_key));
  end if;
  return existing_result;
end $$;

create or replace function public.claim_workflow_events(batch_size int default 20)
returns setof public.workflow_events language plpgsql security definer set search_path=public,pg_catalog as $$
begin
  return query update public.workflow_events w set status='processing',attempt_count=w.attempt_count+1,last_error=null
  where w.id in (select id from public.workflow_events where status in ('pending','failed') and available_at<=now() and attempt_count<5 order by available_at,id for update skip locked limit least(greatest(batch_size,1),100)) returning w.*;
end $$;

create or replace function public.finish_workflow_event(target_id bigint,succeeded boolean,error_text text default null)
returns void language plpgsql security definer set search_path=public,pg_catalog as $$
begin update public.workflow_events set status=case when succeeded then 'processed' else 'failed' end,processed_at=case when succeeded then now() else null end,last_error=case when succeeded then null else left(error_text,1000) end,available_at=case when succeeded then available_at else now()+(least(attempt_count,5)^2||' minutes')::interval end where id=target_id and status='processing'; end $$;

