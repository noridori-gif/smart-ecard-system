-- Workflow Automation V2 foundation and public pledge capture.
-- Forward-only. Deliberately not applied automatically.

create table public.workflow_events (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  event_type text not null check (event_type in ('pledge.submitted','pledge.updated','payment.recorded','payment.completed','message.acknowledgement.requested')),
  entity_type text not null,
  entity_id text,
  source text not null,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  idempotency_key text not null unique,
  status text not null default 'pending' check (status in ('pending','processing','processed','failed')),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  available_at timestamptz not null default now(), processed_at timestamptz, last_error text,
  created_at timestamptz not null default now()
);
create index workflow_events_event_created on public.workflow_events(event_id,created_at desc);
create index workflow_events_claim on public.workflow_events(status,available_at,id) where status in ('pending','failed');

create table public.public_pledge_links (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  token_hash text not null unique check (token_hash ~ '^[a-f0-9]{64}$'),
  title text, message text, default_language text not null default 'sw' check (default_language in ('sw','en')),
  expires_at timestamptz, is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  last_used_at timestamptz, submission_count integer not null default 0 check (submission_count >= 0),
  check (title is null or length(title) <= 120), check (message is null or length(message) <= 500)
);
create index public_pledge_links_event_created on public.public_pledge_links(event_id,created_at desc);
create trigger public_pledge_links_updated_at before update on public.public_pledge_links
for each row execute function public.set_finance_updated_at();

create table public.public_pledge_reviews (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  link_id bigint not null references public.public_pledge_links(id) on delete restrict,
  matched_pledge_ids bigint[] not null default '{}', submitted_data jsonb not null,
  reason text not null check (reason in ('ambiguous_match','adjustment_requested')),
  status text not null default 'pending' check (status in ('pending','resolved','dismissed')),
  idempotency_key text not null unique, created_at timestamptz not null default now(), resolved_at timestamptz
);
create index public_pledge_reviews_event_status on public.public_pledge_reviews(event_id,status,created_at desc);

create table public.public_pledge_rate_limits (
  token_hash text not null, ip_hash text not null, window_started_at timestamptz not null,
  request_count integer not null default 1, primary key(token_hash,ip_hash,window_started_at)
);
revoke all on public.public_pledge_rate_limits from anon,authenticated;

